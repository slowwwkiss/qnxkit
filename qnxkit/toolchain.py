"""QNX 8.0 CMake toolchain files: generation and validation.

The generated file follows the production toolchain file Qt ships
for QNX (``coin/provisioning/common/shared/cmake_toolchain_files/
qnx-toolchain-aarch64le.cmake``) and the QNX example in the CMake
``cmake-toolchains(7)`` manual:

    set(CMAKE_SYSTEM_NAME QNX)
    set(CMAKE_C_COMPILER qcc)
    set(CMAKE_C_COMPILER_TARGET gcc_ntoaarch64le)
    set(CMAKE_CXX_COMPILER q++)
    set(CMAKE_CXX_COMPILER_TARGET gcc_ntoaarch64le)
    set(CMAKE_SYSROOT $ENV{QNX_TARGET})

The ``-V`` target names come from the QNX 8.0 ``gcc``/``qcc``
reference (``qcc -Vgcc_ntoaarch64le`` for AArch64,
``qcc -Vgcc_ntox86_64`` for x86_64).
"""

from __future__ import annotations

import re

from .errors import CheckResult

ARCHES = {
    "aarch64le": {
        "processor": "aarch64le",
        "gcc_target": "gcc_ntoaarch64le",
        "triple": "ntoaarch64",
    },
    "x86_64": {
        "processor": "x86_64",
        "gcc_target": "gcc_ntox86_64",
        "triple": "ntox86_64",
    },
}

GCC_TARGETS = {a["gcc_target"] for a in ARCHES.values()} | {"gcc_ntoarmv7le"}

_SET_RE = re.compile(
    r"set\(\s*([A-Za-z0-9_]+)\s+((?:\"[^\"]*\"|[^)\s]+)(?:\s+(?:\"[^\"]*\"|[^)\s]+))*)\s*\)",
    re.MULTILINE)


def generate_toolchain(arch: str) -> str:
    """Generate a QNX 8.0 CMake toolchain file for ``arch``."""
    if arch not in ARCHES:
        raise ValueError(
            f"unknown arch {arch!r}; known arches: {', '.join(sorted(ARCHES))}")
    a = ARCHES[arch]
    return f"""\
# QNX 8.0 CMake toolchain file ({arch}).
# Generated by qnxkit. Follows the production toolchain file Qt ships
# for QNX (qnx-toolchain-aarch64le.cmake) and the QNX example in the
# CMake cmake-toolchains(7) manual.
# Use: cmake -DCMAKE_TOOLCHAIN_FILE=<this file> -DQNX_TARGET=$QNX_TARGET ...
# Requires QNX SDP 8.0 with QNX_HOST and QNX_TARGET set
# (source $QNX_BASE/qnxsdp-env.sh).

set(CMAKE_SYSTEM_NAME QNX)
set(CMAKE_SYSTEM_VERSION 8.0)
set(CMAKE_SYSTEM_PROCESSOR {a["processor"]})

if (NOT DEFINED CMAKE_FIND_ROOT_PATH_MODE_PROGRAM)
    set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
endif()
if (NOT DEFINED CMAKE_FIND_ROOT_PATH_MODE_LIBRARY)
    set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
endif()
if (NOT DEFINED CMAKE_FIND_ROOT_PATH_MODE_PACKAGE)
    set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
endif()
if (NOT DEFINED CMAKE_FIND_ROOT_PATH_MODE_INCLUDE)
    set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
endif()

set(CMAKE_FIND_ROOT_PATH $ENV{{QNX_TARGET}};$ENV{{QNX_TARGET}}/${{CMAKE_SYSTEM_PROCESSOR}})

set(_qnx_toolchain_arch {a["gcc_target"]})

set(CMAKE_C_COMPILER qcc)
set(CMAKE_C_COMPILER_TARGET ${{_qnx_toolchain_arch}})
set(CMAKE_CXX_COMPILER q++)
set(CMAKE_CXX_COMPILER_TARGET ${{_qnx_toolchain_arch}})

set(CMAKE_STRIP $ENV{{QNX_HOST}}/usr/bin/{a["triple"]}-strip)
set(CMAKE_AR $ENV{{QNX_HOST}}/usr/bin/{a["triple"]}-ar)
set(CMAKE_OBJCOPY $ENV{{QNX_HOST}}/usr/bin/{a["triple"]}-objcopy)

set(CMAKE_SYSROOT $ENV{{QNX_TARGET}})
"""


def parse_toolchain(text: str) -> dict:
    """Parse ``set(VAR value ...)`` statements into {VAR: [values]}."""
    out: dict = {}
    for m in _SET_RE.finditer(text):
        var = m.group(1)
        raw = m.group(2)
        values = re.findall(r'"([^"]*)"|([^\s]+)', raw)
        out[var] = [a or b for a, b in values]
    return out


def _resolve(value: str, variables: dict) -> str:
    """Resolve one level of ${VAR} references against parsed variables."""
    def repl(m):
        return " ".join(variables.get(m.group(1), [""])) or m.group(0)
    prev = None
    out = value
    while prev != out:
        prev = out
        out = re.sub(r"\$\{([A-Za-z0-9_]+)\}", repl, out)
    return out


def check_toolchain(text: str, fname: str = "<toolchain>") -> CheckResult:
    """Validate a CMake toolchain file for QNX 8.0."""
    result = CheckResult()
    variables = parse_toolchain(text)
    if not variables:
        result.add("error", "no-set",
                   "no set(...) statements found — not a toolchain file",
                   fname, 0)
        return result

    def get(var: str) -> str:
        vals = variables.get(var)
        return vals[0] if vals else ""

    system = get("CMAKE_SYSTEM_NAME")
    if not system:
        result.add("error", "no-system-name",
                   "CMAKE_SYSTEM_NAME is not set", fname, 0,
                   "set(CMAKE_SYSTEM_NAME QNX)")
    elif system != "QNX":
        result.add("error", "wrong-system-name",
                   f"CMAKE_SYSTEM_NAME is {system!r}, expected QNX",
                   fname, 0)

    processor = get("CMAKE_SYSTEM_PROCESSOR")
    if not processor:
        result.add("warning", "no-processor",
                   "CMAKE_SYSTEM_PROCESSOR is not set", fname, 0,
                   "set it to aarch64le or x86_64")

    c_compiler = get("CMAKE_C_COMPILER")
    if not c_compiler:
        result.add("error", "no-c-compiler",
                   "CMAKE_C_COMPILER is not set", fname, 0,
                   "set(CMAKE_C_COMPILER qcc)")
    elif c_compiler != "qcc":
        result.add("error", "wrong-c-compiler",
                   f"CMAKE_C_COMPILER is {c_compiler!r}, expected qcc",
                   fname, 0)

    cxx_compiler = get("CMAKE_CXX_COMPILER")
    if not cxx_compiler:
        result.add("error", "no-cxx-compiler",
                   "CMAKE_CXX_COMPILER is not set", fname, 0,
                   "set(CMAKE_CXX_COMPILER q++)")
    elif cxx_compiler not in ("q++", "QCC"):
        result.add("error", "wrong-cxx-compiler",
                   f"CMAKE_CXX_COMPILER is {cxx_compiler!r}, expected q++",
                   fname, 0)

    for var in ("CMAKE_C_COMPILER_TARGET", "CMAKE_CXX_COMPILER_TARGET"):
        raw = get(var)
        if not raw:
            result.add("error", f"no-{var.lower().replace('_', '-')}",
                       f"{var} is not set", fname, 0,
                       "set it to gcc_ntoaarch64le or gcc_ntox86_64")
            continue
        target = _resolve(raw, variables)
        if target not in GCC_TARGETS:
            result.add("error", "unknown-target",
                       f"{var} is {target!r}, not a known QNX 8.0 target",
                       fname, 0,
                       f"known targets: {', '.join(sorted(GCC_TARGETS))}")
        elif processor:
            expected = next(
                (a["gcc_target"] for a in ARCHES.values()
                 if a["processor"] == processor), None)
            if expected and target != expected:
                result.add("error", "arch-mismatch",
                           f"{var} is {target!r} but CMAKE_SYSTEM_PROCESSOR "
                           f"is {processor!r}",
                           fname, 0,
                           f"for {processor} use {expected}")

    sysroot = get("CMAKE_SYSROOT")
    if not sysroot:
        result.add("warning", "no-sysroot",
                   "CMAKE_SYSROOT is not set", fname, 0,
                   "set(CMAKE_SYSROOT $ENV{QNX_TARGET})")
    elif "$ENV{QNX_TARGET}" not in sysroot and sysroot != "$ENV{QNX_TARGET}":
        result.add("warning", "sysroot-not-qnx-target",
                   f"CMAKE_SYSROOT is {sysroot!r}, expected $ENV{{QNX_TARGET}}",
                   fname, 0)

    find_root = get("CMAKE_FIND_ROOT_PATH")
    if find_root and "$ENV{QNX_TARGET}" not in find_root:
        result.add("warning", "find-root-not-qnx-target",
                   "CMAKE_FIND_ROOT_PATH does not mention $ENV{QNX_TARGET}",
                   fname, 0)

    for var in ("CMAKE_STRIP", "CMAKE_AR", "CMAKE_OBJCOPY"):
        if not get(var):
            result.add("warning", f"no-{var.lower().replace('_', '-')}",
                       f"{var} is not set (optional but recommended)",
                       fname, 0,
                       f"set it to $ENV{{QNX_HOST}}/usr/bin/<triple>-"
                       f"{var.split('_')[-1].lower()}")
    if get("CMAKE_SYSTEM_VERSION") and get("CMAKE_SYSTEM_VERSION") != "8.0":
        result.add("warning", "version-not-8.0",
                   f"CMAKE_SYSTEM_VERSION is "
                   f"{get('CMAKE_SYSTEM_VERSION')!r}, expected 8.0",
                   fname, 0)

    detected = None
    for arch, a in ARCHES.items():
        if _resolve(get("CMAKE_C_COMPILER_TARGET"), variables) == a["gcc_target"]:
            detected = arch
    result.summary = {"arch": detected, "processor": processor or None}
    return result
